def sheet(title, cols, rows, first=False, date_cols=(), height=34):
    """cols: list of (header, width, main?)"""
    ws = wb.active if first else wb.create_sheet(title)
    ws.title = title
    ws.append([c[0] for c in cols])
    for cell, (_, w, main) in zip(ws[1], cols):
        cell.font, cell.fill = MAIN if main else OPT
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center"); cell.border = B
        ws.column_dimensions[cell.column_letter].width = w
    ws.row_dimensions[1].height = height
    ws.freeze_panes = "A2"
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2, max_row=max(ws.max_row, 60)):
        for i, c in enumerate(row):
            c.border = B; c.alignment = wrap
            if i in date_cols:
                c.number_format = "DD.MM.YYYY"
    return ws


